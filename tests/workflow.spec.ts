import {test,expect} from '@playwright/test';
test('produit → rédaction → bibliothèque → calendrier, persistance et exports',async({page})=>{
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Chaque contenu, une opportunité.'})).toBeVisible();
 await page.getByRole('navigation').getByRole('button',{name:'Mes produits'}).click();
 await page.getByRole('button',{name:'Ajouter un produit',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Nom du produit').fill('Parfum test');
 await dialog.getByLabel('Prix (FCFA)').fill('12000');
 await dialog.getByLabel('Stock disponible').fill('5');
 await dialog.getByLabel('Description vérifiée').fill('Flacon de 50 ml.');
 await dialog.getByRole('button',{name:'Enregistrer le produit'}).click();
 await expect(page.getByRole('heading',{name:'Parfum test',exact:true})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('heading',{name:'Parfum test',exact:true})).toBeVisible();
 await page.locator('.product-card').filter({has:page.getByRole('heading',{name:'Parfum test',exact:true})}).getByRole('button',{name:'Créer un contenu'}).click();
 await page.getByLabel('Que souhaitez-vous raconter ?').fill('Découvrez notre sélection cette semaine.');
 await page.getByRole('button',{name:'Générer mes publications'}).click();
 await expect(page.getByLabel('Texte Facebook')).toHaveValue(/Parfum test/);
 await page.getByRole('button',{name:'3 variantes',exact:true}).click();
 await expect(page.getByRole('button',{name:'Variante 3',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Variante 2',exact:true}).click();
 await page.getByRole('button',{name:'Enregistrer',exact:true}).click();
 await page.getByRole('button',{name:'Au calendrier'}).click();
 await page.getByRole('button',{name:'Planifier ce contenu'}).click();
 await page.getByRole('navigation').getByRole('button',{name:'Bibliothèque',exact:true}).click();
 await expect(page.locator('.saved-copy')).toContainText('Flacon de 50 ml.');
 await page.getByRole('navigation').getByRole('button',{name:'Calendrier éditorial'}).click();
 await expect(page.locator('.calendar-event').filter({hasText:'Parfum test'})).toBeVisible();
 await page.getByRole('button',{name:'Exporter',exact:true}).click();
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'Télécharger le CSV'}).click();
 expect((await download).suggestedFilename()).toBe('nickshop-calendrier.csv');
});
