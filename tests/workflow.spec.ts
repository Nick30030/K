test('API : modèles locaux et refus des requêtes non valides',async({request})=>{
 const status=await request.get('/api/status');expect(status.ok()).toBeTruthy();
 const r=await request.post('/api/generate',{data:{kind:'copy',product:{name:'Parfum',price:12000,stock:2,active:true},original:'Mon texte'}});expect(r.ok()).toBeTruthy();expect((await r.json()).result.WhatsApp).toContain('Parfum');
 const invalid=await request.post('/api/generate',{data:{kind:'other'}});expect(invalid.status()).toBe(400);
 const stock=await request.post('/api/generate',{data:{kind:'copy',product:{name:'Parfum',price:12000,stock:0,active:true}}});expect(stock.status()).toBe(400);
 const cross=await request.post('/api/generate',{headers:{Origin:'https://untrusted.example'},data:{kind:'copy',original:'x'}});expect(cross.status()).toBe(403);
});
test('planning 15 jours, déplacement et PDF complet',async({page})=>{
 await page.goto('/?page=calendar');
 await page.getByRole('button',{name:'Créer un planning'}).click();
 await page.getByLabel('Premier jour').fill('2026-11-01');
 await page.getByLabel('Durée',{exact:true}).selectOption('15');
 await page.getByLabel('Publications par semaine').fill('7');
 await page.getByRole('button',{name:'Générer le planning'}).click();
 await expect(page.locator('.calendar-event')).toHaveCount(15);
 const first=page.locator('.calendar-event').first();const id=await first.getAttribute('data-post-id');
 await first.dragTo(page.locator('.calendar-day').filter({has:page.getByRole('button',{name:'Ajouter le 2026-11-03',exact:true})}));
 await page.locator('.calendar-day').filter({has:page.getByRole('button',{name:'Ajouter le 2026-11-03',exact:true})}).locator(`[data-post-id="${id}"]`).click();
 await expect(page.getByLabel('Date',{exact:true})).toHaveValue('2026-11-03');
 await page.getByRole('dialog').getByRole('button',{name:'Enregistrer',exact:true}).click();
 await page.emulateMedia({media:'print'});
 await expect(page.locator('.print-export')).toBeVisible();
 await expect(page.locator('.print-post')).toHaveCount(15);
 await expect(page.locator('.print-post').first()).toContainText('Écrivez-nous sur WhatsApp');
});
